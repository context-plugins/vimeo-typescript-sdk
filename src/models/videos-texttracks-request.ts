import * as s from "../core/validation/index.js";
import type { Schema } from "../core/validation/schema.js";
import { type29Schema, type Type29 } from "./type29.js";

export type VideosTexttracksRequest = {
  /**
   * Whether the current text track is the *active text track,* or the one that appears in the
   * player. Only one text track per language and type can be active.
   */
  active?: boolean;
  /**
   * Whether the text track was uploaded automatically by the Seshat audio annotation management
   * platform.
   */
  isAutoGenerated?: boolean;
  /**
   * Whether the text track was uploaded by the Seshat audio annotation management platform after
   * the user edited their transcript.
   */
  isEdited?: boolean;
  /**
   * The language of the text track. For a full list of supported languages, use the
   * [`/languages?filter=texttracks`](https://developer.vimeo.com/api/reference/videos#get_languages)
   * endpoint.
   */
  language: string;
  /** The name of the text track. */
  name: string;
  /**
   * The type of text track.
   *
   * Option descriptions:
   *  * `captions` - The text track is the captions type.
   *  * `chapters` - The text track is the chapters type.
   *  * `descriptions` - The text track is the descriptions type.
   *  * `metadata` - The text track is the metadata type.
   *  * `subtitles` - The text track is the subtitles type.
   */
  type: Type29;
};

export const videosTexttracksRequestSchema: Schema<VideosTexttracksRequest> =
  s.object<VideosTexttracksRequest>({
    active: s.optional(s.boolean()),
    isAutoGenerated: s.optional(s.boolean()),
    isEdited: s.optional(s.boolean()),
    language: s.string(),
    name: s.string(),
    type: type29Schema,
    _keysMap: {
      isAutoGenerated: "is_auto_generated",
      isEdited: "is_edited",
    },
  });
