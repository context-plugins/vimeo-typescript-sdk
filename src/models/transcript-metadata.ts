import * as s from "../core/validation/index.js";
import type { Schema } from "../core/validation/schema.js";

export type TranscriptMetadata = {
  autogenerated: boolean;
  clipId: number;
  containerId: string;
  deleted: boolean;
  enabled: boolean;
  id: string;
  kind: string;
  language: string;
  speakerCount: number;
  texttrackId: number;
  transcriptStatusUuid: string;
  wordCount: number;
};

export const transcriptMetadataSchema: Schema<TranscriptMetadata> = s.object<TranscriptMetadata>({
  autogenerated: s.boolean(),
  clipId: s.number(),
  containerId: s.string(),
  deleted: s.boolean(),
  enabled: s.boolean(),
  id: s.string(),
  kind: s.string(),
  language: s.string(),
  speakerCount: s.number(),
  texttrackId: s.number(),
  transcriptStatusUuid: s.string(),
  wordCount: s.number(),
  _keysMap: {
    clipId: "clip_id",
    containerId: "container_id",
    speakerCount: "speaker_count",
    texttrackId: "texttrack_id",
    transcriptStatusUuid: "transcript_status_uuid",
    wordCount: "word_count",
  },
});
