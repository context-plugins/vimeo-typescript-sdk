import * as s from "../core/validation/index.js";
import type { Schema } from "../core/validation/schema.js";
import { download1Schema, type Download1 } from "./download1.js";
import { language2Schema, type Language2 } from "./language2.js";
import { provenanceSchema, type Provenance } from "./provenance.js";
import { quotaSchema, type Quota } from "./quota.js";
import { transcode1Schema, type Transcode1 } from "./transcode1.js";
import { type11Schema, type Type11 } from "./type11.js";

export type AlternateAudioTrack = {
  /** Whether the audio track is enabled. */
  active: boolean;
  /** The downloads that are available for the audio track. */
  download: Download1[];
  /** The language of the audio track. */
  language: Language2;
  /**
   * The origin of the audio track.
   *
   * Option descriptions:
   *  * `ai_generated` - The audio track is generated by AI.
   *  * `user_uploaded` - The audio track is uploaded by a user.
   *  * `user_uploaded_and_ai_generated` - The audio track is uploaded by a user and contains
   *    AI-generated content.
   */
  provenance: Provenance;
  /** The quota parameters for the audio tracks available for this version. */
  quota: Quota;
  /** The transcode information for the audio track. */
  transcode: Transcode1;
  /**
   * The type of audio track.
   *
   * Option descriptions:
   *  * `commentary` - The audio track is a commentary.
   *  * `descriptive` - The audio track is descriptive for accessibility.
   *  * `main` - The audio track is dubbed audio.
   *  * `unknown` - The audio track category is unknown.
   */
  type: Type11;
  /** The upload information for the audio track. */
  upload: Record<string, unknown>;
  /** The audio track's canonical relative URI. */
  uri: string;
};

export const alternateAudioTrackSchema: Schema<AlternateAudioTrack> = s.object<AlternateAudioTrack>({
  active: s.boolean(),
  download: s.array(s.lazy(() => download1Schema)),
  language: language2Schema,
  provenance: provenanceSchema,
  quota: quotaSchema,
  transcode: transcode1Schema,
  type: type11Schema,
  upload: s.record(s.string(), s.unknown()),
  uri: s.string(),
});
