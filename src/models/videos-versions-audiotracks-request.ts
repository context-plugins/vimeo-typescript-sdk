import * as s from "../core/validation/index.js";
import type { Schema } from "../core/validation/schema.js";
import { provenance2Schema, type Provenance2 } from "./provenance2.js";
import { type57Schema, type Type57 } from "./type57.js";
import { upload5Schema, type Upload5 } from "./upload5.js";

export type VideosVersionsAudiotracksRequest = {
  /** Whether the audio track is enabled. */
  active?: boolean;
  /**
   * The language of the audio track. For a full list of supported languages, use the
   * [`/languages?filter=audiotracks`](https://developer.vimeo.com/api/reference/videos#get_languages)
   * method.
   */
  languageCode?: string;
  /**
   * The origin of the audio track.
   *
   * Option descriptions:
   *  * `ai_generated` - The audio track is generated by AI.
   *  * `user_uploaded` - The audio track is uploaded by a user.
   *  * `user_uploaded_and_ai_generated` - The audio track is uploaded by a user and contains AI
   *    content.
   */
  provenance?: Provenance2;
  /**
   * The type of audio track.
   *
   * Option descriptions:
   *  * `commentary` - The audio track is the commentary type.
   *  * `descriptive` - The audio track is the descriptive type.
   *  * `main` - The audio track is the main type.
   */
  type?: Type57;
  upload: Upload5;
};

export const videosVersionsAudiotracksRequestSchema: Schema<VideosVersionsAudiotracksRequest> =
  s.object<VideosVersionsAudiotracksRequest>({
    active: s.optional(s.boolean()),
    languageCode: s.optional(s.string()),
    provenance: s.optional(s.lazy(() => provenance2Schema)),
    type: s.optional(s.lazy(() => type57Schema)),
    upload: upload5Schema,
    _keysMap: {
      languageCode: "language_code",
    },
  });
