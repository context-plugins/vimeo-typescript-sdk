import * as s from "../core/validation/index.js";
import type { Schema } from "../core/validation/schema.js";
import { kind1Schema, type Kind1 } from "./kind1.js";
import { segmentLineSchema, type SegmentLine } from "./segment-line.js";
import {
  segmentTranslationMetadataSchema,
  type SegmentTranslationMetadata,
} from "./segment-translation-metadata.js";
import { segmentWordsSchema, type SegmentWords } from "./segment-words.js";

export type Segment = {
  autogenerated: boolean;
  cueEnd: number;
  cueStart: number;
  enabled: boolean;
  id: string;
  kind: Kind1;
  language: string;
  lines: SegmentLine[];
  speaker: string | null;
  textTrackUri: string;
  translationMetadata?: SegmentTranslationMetadata;
  videoUri?: string;
  words: SegmentWords[];
};

export const segmentSchema: Schema<Segment> = s.object<Segment>({
  autogenerated: s.boolean(),
  cueEnd: s.number(),
  cueStart: s.number(),
  enabled: s.boolean(),
  id: s.string(),
  kind: kind1Schema,
  language: s.string(),
  lines: s.array(s.lazy(() => segmentLineSchema)),
  speaker: s.nullable(s.string()),
  textTrackUri: s.string(),
  translationMetadata: s.optional(s.lazy(() => segmentTranslationMetadataSchema)),
  videoUri: s.optional(s.string()),
  words: s.array(s.lazy(() => segmentWordsSchema)),
  _keysMap: {
    cueEnd: "cue_end",
    cueStart: "cue_start",
    textTrackUri: "text_track_uri",
    translationMetadata: "translation_metadata",
    videoUri: "video_uri",
  },
});
